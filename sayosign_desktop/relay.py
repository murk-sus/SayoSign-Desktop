"""Anisette settings and the local anisette server ("relay") SayoSign Desktop can run.

Apple stopped accepting anisette generated by Android libraries in October 2026, which is
the only kind a Linux or Windows PC can produce on its own. So instead of a doomed local
Android server, the PC runs a relay: it speaks the full anisette v3 protocol to the iPhone
on the local network and forwards it to a Mac-based server (a public one or your own).
The iPhone points SayoSign at the PC once (by scanning a QR code) and keeps working even if
you later switch the upstream server on the PC.
"""
import asyncio
import io
import json
import socket
import time
from pathlib import Path

import aiohttp
from aiohttp import web

from .anisette import PUBLIC_SERVERS, Anisette, AnisetteError

DEFAULT_PORT = 6969


VPN_PREFIXES = ("tun", "tap", "wg", "amn", "utun", "ppp", "tailscale", "zt", "docker", "veth", "br-", "virbr", "vmnet", "lo")


def lan_ips():
    """IPv4 addresses on real local networks, best first (VPN tunnels and /32 links skipped)."""
    import ipaddress
    import re
    import subprocess
    import sys
    found = []
    try:
        if sys.platform.startswith("linux"):
            out = subprocess.run(["ip", "-4", "-o", "addr", "show"], capture_output=True, text=True, timeout=3).stdout
            for line in out.splitlines():
                parts = line.split()
                name, cidr = parts[1], parts[3]
                ip, plen = cidr.split("/")
                found.append((name, ip, int(plen)))
        elif sys.platform == "darwin":
            out = subprocess.run(["ifconfig"], capture_output=True, text=True, timeout=3).stdout
            name = ""
            for line in out.splitlines():
                if line and not line[0].isspace():
                    name = line.split(":")[0]
                m = re.search(r"inet (\d+\.\d+\.\d+\.\d+) netmask 0x([0-9a-f]+)", line)
                if m:
                    found.append((name, m.group(1), bin(int(m.group(2), 16)).count("1")))
    except Exception:
        pass
    if not found:
        try:
            for info in socket.getaddrinfo(socket.gethostname(), None, socket.AF_INET):
                found.append(("", info[4][0], 24))
        except OSError:
            pass
    good = []
    for name, ip, plen in found:
        addr = ipaddress.ip_address(ip)
        if addr.is_loopback or not addr.is_private or plen >= 31 or name.startswith(VPN_PREFIXES):
            continue
        rank = 0 if ip.startswith("192.168.") else 1 if ip.startswith("10.") else 2
        good.append((rank, ip))
    ips = [ip for _, ip in sorted(set(good))]
    return ips or ["127.0.0.1"]


def lan_ip():
    return lan_ips()[0]


def qr_svg(text):
    import qrcode
    import qrcode.image.svg
    img = qrcode.make(text, image_factory=qrcode.image.svg.SvgPathImage, box_size=8, border=2)
    buf = io.BytesIO()
    img.save(buf)
    return buf.getvalue().decode()


class AnisetteConfig:
    """Which anisette server SayoSign uses, and whether the relay runs."""

    def __init__(self, path: Path, state_dir: Path):
        self.path = path
        self.state_dir = state_dir
        try:
            self.data = json.loads(path.read_text())
        except Exception:
            self.data = {}
        self.data.setdefault("server", PUBLIC_SERVERS[0][1])
        self.data.setdefault("relay", False)
        self.data.setdefault("port", DEFAULT_PORT)

    def save(self):
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.path.write_text(json.dumps(self.data, indent=1))

    @property
    def server(self):
        return self.data["server"]

    def anisette(self, server=None):
        return Anisette(server or self.server, self.state_dir)


async def pick_best(state_dir):
    """Checks the public Mac servers in parallel and returns the fastest one that works."""
    async def probe(name, url):
        t = time.monotonic()
        st = await asyncio.to_thread(Anisette(url, state_dir).status)
        st["name"] = name
        st["ms"] = round((time.monotonic() - t) * 1000)
        return st
    results = await asyncio.gather(*(probe(n, u) for n, u in PUBLIC_SERVERS))
    ok = sorted((r for r in results if r.get("ok") and r.get("mac")), key=lambda r: r["ms"])
    return (ok[0] if ok else None), results


class Relay:
    """The local anisette server for the iPhone."""

    def __init__(self, config: AnisetteConfig):
        self.config = config
        self.runner = None
        self.started = None
        self.requests = 0

    @property
    def running(self):
        return self.runner is not None

    @property
    def url(self):
        return f"http://{lan_ip()}:{self.config.data['port']}"

    def info(self):
        url = self.url
        link = f"sayosign://anisette?server={url}"
        port = self.config.data["port"]
        return {"running": self.running, "url": url, "link": link, "port": port,
                "addresses": [f"http://{ip}:{port}" for ip in lan_ips()],
                "upstream": self.config.server, "requests": self.requests,
                "since": self.started, "qr": qr_svg(link) if self.running else None}

    async def start(self):
        if self.running:
            return
        app = web.Application()
        app.router.add_get("/", self.v1)
        app.router.add_get("/v3/client_info", self.client_info)
        app.router.add_post("/v3/get_headers", self.get_headers)
        app.router.add_get("/v3/provisioning_session", self.provisioning)
        app.router.add_get("/sayosign", self.status)
        runner = web.AppRunner(app, access_log=None)
        await runner.setup()
        site = web.TCPSite(runner, "0.0.0.0", self.config.data["port"])
        try:
            await site.start()
        except OSError as e:
            await runner.cleanup()
            raise AnisetteError(f"Port {self.config.data['port']} is busy: {e}")
        self.runner = runner
        self.started = time.time()

    async def stop(self):
        if self.runner:
            await self.runner.cleanup()
        self.runner = None
        self.started = None

    # ---------- handlers ----------
    def _up(self, path):
        return self.config.server.rstrip("/") + path

    def _json(self, data):
        return web.json_response(data, headers={"Implementation-Version": "SayoSign Desktop relay"})

    async def client_info(self, request):
        self.requests += 1
        async with aiohttp.ClientSession() as s:
            async with s.get(self._up("/v3/client_info"), timeout=aiohttp.ClientTimeout(total=20)) as r:
                return self._json(await r.json(content_type=None))

    async def get_headers(self, request):
        self.requests += 1
        body = await request.read()
        async with aiohttp.ClientSession() as s:
            async with s.post(self._up("/v3/get_headers"), data=body, headers={"Content-Type": "application/json"},
                              timeout=aiohttp.ClientTimeout(total=30)) as r:
                return self._json(await r.json(content_type=None))

    async def provisioning(self, request):
        """Bridges the provisioning WebSocket between the iPhone and the upstream server."""
        self.requests += 1
        client = web.WebSocketResponse(heartbeat=20)
        await client.prepare(request)
        up_url = self._up("/v3/provisioning_session").replace("https://", "wss://").replace("http://", "ws://")
        async with aiohttp.ClientSession() as s:
            async with s.ws_connect(up_url, heartbeat=20) as up:
                async def pump(src, dst):
                    async for m in src:
                        if m.type == aiohttp.WSMsgType.TEXT:
                            await dst.send_str(m.data)
                        elif m.type == aiohttp.WSMsgType.BINARY:
                            await dst.send_bytes(m.data)
                        else:
                            break
                    await dst.close()
                await asyncio.gather(pump(up, client), pump(client, up), return_exceptions=True)
        return client

    async def v1(self, request):
        """v1 endpoint for older clients: headers made from this PC's own identity."""
        self.requests += 1
        try:
            a = self.config.anisette()
            h = await asyncio.to_thread(a.headers)
        except Exception as e:
            return self._json({"error": str(e)})
        return self._json({**h, "X-MMe-Client-Info": a.client_info})

    async def status(self, request):
        return self._json({"relay": "SayoSign Desktop", "upstream": self.config.server, "requests": self.requests})
